import { mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { createContext, runInContext } from 'node:vm';

import { parse } from 'acorn';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { parse as parseYaml } from 'yaml';

import {
  bundle,
  ECMA_VERSION,
  ESBUILD_TARGET,
  GLOBAL_NAME,
  REPO_ROOT,
  renderFooter,
  resolveOutDir,
} from '../../scripts/bundle.ts';
import { ENTRY_POINTS } from '../../src/entry/entry-points.ts';
import * as main from '../../src/entry/main.ts';

const FIXTURE_CONFIG = join(REPO_ROOT, 'test', 'fixtures', 'config', 'valid.yaml');
const FIXTURE_RULE_IDS = ['fixture-approval', 'fixture-bill', 'fixture-newsletter'];

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null;
}

/** Calls the global function `name` in `scope`, failing if it isn't a function. */
function callGlobal(scope: Record<string, unknown>, name: string): unknown {
  const fn = scope[name];
  if (typeof fn !== 'function') {
    throw new Error(`${name} is not a global function`);
  }
  return Reflect.apply(fn, undefined, []);
}

/** Evaluates `code` as a classic script in a fresh context with no module system. */
function evaluate(code: string): Record<string, unknown> {
  const scope: Record<string, unknown> = createContext({});
  runInContext(code, scope);
  return scope;
}

describe('renderFooter', () => {
  it('writes one declaration per name, in order, after a comment line', () => {
    expect(renderFooter(['onTrigger', 'install'])).toBe(
      [
        '// Global functions generated by scripts/bundle.ts. Do not edit.',
        'function onTrigger() { return JevGmailClassifier.onTrigger(); }',
        'function install() { return JevGmailClassifier.install(); }',
        '',
      ].join('\n'),
    );
  });

  it('writes only the comment line for an empty list', () => {
    expect(renderFooter([])).toBe(
      '// Global functions generated by scripts/bundle.ts. Do not edit.\n',
    );
  });

  it('rejects a name that is not a JavaScript identifier', () => {
    expect(() => renderFooter(['on-trigger'])).toThrow(/not a JavaScript identifier/);
  });
});

describe('resolveOutDir', () => {
  it('refuses the repository root and its ancestors', () => {
    expect(() => resolveOutDir('.')).toThrow(/repository root/);
    expect(() => resolveOutDir(dirname(REPO_ROOT))).toThrow(/repository root/);
  });

  it('resolves a relative directory against the repository root', () => {
    expect(resolveOutDir('dist')).toBe(join(REPO_ROOT, 'dist'));
  });
});

describe('bundle()', () => {
  let outDir: string;
  let code: string;

  beforeAll(async () => {
    outDir = mkdtempSync(join(tmpdir(), 'jev-bundle-'));
    writeFileSync(join(outDir, 'stale.js'), '// left over from an earlier build\n');
    const embeddedConfig: unknown = parseYaml(readFileSync(FIXTURE_CONFIG, 'utf8'));
    await bundle({ outDir, embeddedConfig, configSourceName: 'valid.yaml' });
    code = readFileSync(join(outDir, 'Code.js'), 'utf8');
  });

  afterAll(() => {
    rmSync(outDir, { recursive: true, force: true });
  });

  it('writes exactly Code.js and appsscript.json, removing stale files', () => {
    expect(readdirSync(outDir).sort()).toEqual(['Code.js', 'appsscript.json']);
  });

  it('copies the manifest byte for byte', () => {
    expect(readFileSync(join(outDir, 'appsscript.json'))).toEqual(
      readFileSync(join(REPO_ROOT, 'appsscript.json')),
    );
  });

  it('is one IIFE assigned to the global, ending with the generated footer', () => {
    expect(code.startsWith(`"use strict";\nvar ${GLOBAL_NAME} = (() => {\n`)).toBe(true);
    expect(code.endsWith(`})();\n\n${renderFooter(ENTRY_POINTS)}`)).toBe(true);
  });

  it(`parses as an ES${String(ECMA_VERSION)} script (target ${ESBUILD_TARGET})`, () => {
    // A classic script: any `import`, `export`, `#private`, class field or
    // newer syntax fails to parse.
    expect(() => parse(code, { ecmaVersion: ECMA_VERSION, sourceType: 'script' })).not.toThrow();
  });

  it('declares a global function for every entry point', () => {
    const scope = evaluate(code);
    for (const name of ENTRY_POINTS) {
      expect(typeof scope[name], name).toBe('function');
    }
  });

  it(`exposes exactly the entry points on ${GLOBAL_NAME}`, () => {
    const exposed = evaluate(code)[GLOBAL_NAME];
    expect(isRecord(exposed)).toBe(true);
    expect(new Set(Object.keys(isRecord(exposed) ? exposed : {}))).toEqual(new Set(ENTRY_POINTS));
  });

  it('embeds the config it was given', () => {
    for (const id of FIXTURE_RULE_IDS) {
      expect(code).toContain(`"id": "${id}"`);
    }
  });

  it('reaches the embedded config from the entry points', () => {
    const scope = evaluate(code);
    for (const name of ENTRY_POINTS) {
      expect(callGlobal(scope, name), name).toMatchObject({ configEmbedded: true });
    }
  });

  it('calls each placeholder in main.ts through the footer', () => {
    const scope = evaluate(code);
    for (const name of ENTRY_POINTS) {
      expect(callGlobal(scope, name), name).toEqual(main[name]());
    }
  });

  it(`calls whatever ${GLOBAL_NAME} holds at call time`, () => {
    const scope = evaluate(code);
    scope[GLOBAL_NAME] = Object.fromEntries(
      ENTRY_POINTS.map((name) => [name, () => `sentinel:${name}`]),
    );
    for (const name of ENTRY_POINTS) {
      expect(callGlobal(scope, name)).toBe(`sentinel:${name}`);
    }
  });
});
